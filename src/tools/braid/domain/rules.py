from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any

from braid.domain.model import BraidError, _resolved, is_legacy_skills_source

if TYPE_CHECKING:
    from collections.abc import Iterable, Mapping

__all__ = [
    "DIRECTORY_HOSTS",
    "GENERATED_HEADER",
    "GENERATED_LIMIT",
    "HOST_INSTRUCTION_PATHS",
    "KNOWN_HOSTS",
    "SINGLE_FILE_HOSTS",
    "RuleInventory",
    "RuleState",
    "discover_rules",
    "render_host_file",
]

RULE_NAME = re.compile(r"[a-z0-9-]+")
KNOWN_HOSTS: tuple[str, ...] = ("claude", "kiro", "codex", "copilot", "pi", "gemini")
SINGLE_FILE_HOSTS: tuple[str, ...] = ("codex", "copilot", "pi", "gemini")
DIRECTORY_HOSTS: tuple[str, ...] = ("claude", "kiro")
HOST_INSTRUCTION_PATHS: dict[str, Path] = {  # relative to Path.home()
    "codex": Path(".codex") / "AGENTS.md",
    "copilot": Path(".copilot") / "copilot-instructions.md",
    "pi": Path(".pi") / "agent" / "AGENTS.md",
    "gemini": Path(".gemini") / "GEMINI.md",
}
GENERATED_HEADER = "<!-- Generated by braid. Edit the rule sources, not this file. -->"
GENERATED_LIMIT = 32768
_STATE_KEYS = ("union", "hosts", "projected", "generated", "instructions")


@dataclass(frozen=True)
class RuleInventory:
    shared: dict[str, Path]  # name -> resolved rule directory
    hosts: dict[str, dict[str, Path]]  # host -> name -> resolved rule directory; only hosts with rules

    @property
    def empty(self) -> bool:
        return not self.shared and not self.hosts


def _flat(value: object, allowed: tuple[str, ...] | None = None) -> bool:
    return isinstance(value, dict) and all(
        isinstance(key, str) and isinstance(item, str) and (allowed is None or key in allowed)
        for key, item in value.items()
    )


def _nested(value: object, allowed: tuple[str, ...]) -> bool:
    return isinstance(value, dict) and all(key in allowed and _flat(links) for key, links in value.items())


@dataclass(frozen=True)
class RuleState:
    union: dict[str, str]  # name -> source rule dir
    hosts: dict[str, dict[str, str]]  # host -> name -> source rule dir
    projected: dict[str, dict[str, str]]  # "claude" | "kiro" -> name -> union-view RULE.md path
    generated: dict[str, str]  # single-file host -> generated AGENTS.md path
    instructions: dict[str, str]  # single-file host -> host instruction link path

    @classmethod
    def empty(cls) -> RuleState:
        return cls(union={}, hosts={}, projected={}, generated={}, instructions={})

    def as_json(self) -> dict[str, Any]:
        return {
            "union": self.union,
            "hosts": self.hosts,
            "projected": self.projected,
            "generated": self.generated,
            "instructions": self.instructions,
        }

    @classmethod
    def from_json(cls, payload: object, path: Path) -> RuleState:
        if not isinstance(payload, dict) or not all(key in payload for key in _STATE_KEYS):
            raise BraidError(f"invalid rules state in {path}")
        union, hosts, projected, generated, instructions = (payload[key] for key in _STATE_KEYS)
        if not (
            _flat(union)
            and _nested(hosts, KNOWN_HOSTS)
            and _nested(projected, DIRECTORY_HOSTS)
            and _flat(generated, SINGLE_FILE_HOSTS)
            and _flat(instructions, SINGLE_FILE_HOSTS)
        ):
            raise BraidError(f"invalid rules state in {path}")
        return cls(
            union=dict(union),
            hosts={host: dict(links) for host, links in hosts.items()},
            projected={host: dict(links) for host, links in projected.items()},
            generated=dict(generated),
            instructions=dict(instructions),
        )


def _read_rule(rule_file: Path) -> str:
    try:
        return rule_file.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise BraidError(f"cannot read {rule_file}: {error}") from error


def _rule_candidates(rules_directory: Path) -> list[Path]:
    if not rules_directory.is_dir():
        return []
    kept: list[Path] = []
    for candidate in sorted(rules_directory.iterdir(), key=lambda path: path.name):
        if candidate.is_symlink() or candidate.name.startswith(".") or not candidate.is_dir():
            continue
        if not (candidate / "RULE.md").is_file():
            continue
        if not RULE_NAME.fullmatch(candidate.name):
            raise BraidError(f"invalid rule name {candidate.name!r}: {candidate}")
        _read_rule(candidate / "RULE.md")
        kept.append(candidate)
    return kept


def _host_directories(source: Path) -> list[Path]:
    hosts_directory = source / "hosts"
    if not hosts_directory.is_dir():
        return []
    kept: list[Path] = []
    for entry in sorted(hosts_directory.iterdir(), key=lambda path: path.name):
        if entry.name.startswith(".") or entry.is_symlink() or not entry.is_dir():
            continue
        if entry.name not in KNOWN_HOSTS:
            raise BraidError(f"unknown host directory: {entry}")
        kept.append(entry)
    return kept


def discover_rules(sources: Iterable[Path]) -> RuleInventory:
    shared: dict[str, Path] = {}
    hosts: dict[str, dict[str, Path]] = {}
    shared_owners: dict[str, Path] = {}
    host_owners: dict[str, dict[str, Path]] = {}
    any_host_owner: dict[str, Path] = {}
    seen_sources: set[Path] = set()

    for configured in sources:
        source = _resolved(configured)
        if source in seen_sources or is_legacy_skills_source(source):
            continue
        seen_sources.add(source)
        for candidate in _rule_candidates(source / "rules"):
            name = candidate.name
            first = shared_owners.get(name) or any_host_owner.get(name)
            if first is not None:
                raise BraidError(f"duplicate rule name {name!r}: {first} and {configured}")
            shared[name] = _resolved(candidate)
            shared_owners[name] = source
        for entry in _host_directories(source):
            owners = host_owners.setdefault(entry.name, {})
            for candidate in _rule_candidates(entry / "rules"):
                name = candidate.name
                first = shared_owners.get(name) or owners.get(name)
                if first is not None:
                    raise BraidError(f"duplicate rule name {name!r}: {first} and {configured}")
                hosts.setdefault(entry.name, {})[name] = _resolved(candidate)
                owners[name] = source
                any_host_owner.setdefault(name, source)
    return RuleInventory(shared=shared, hosts=hosts)


def render_host_file(shared: Mapping[str, Path], host_rules: Mapping[str, Path]) -> str:
    bodies = [_read_rule(directory / "RULE.md").rstrip() for directory in (*shared.values(), *host_rules.values())]
    return "\n\n".join([GENERATED_HEADER, *(body for body in bodies if body)]) + "\n"
